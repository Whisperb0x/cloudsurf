"""CloudSurf build script.

Generates everything the sim project needs that is not hand-written (the WASM
module, the toolbar panel page and its definition) into msfs-project/, and
installs the package the sim built into your Community folder.

  python build.py              generate module + panel into msfs-project/
  python build.py --install    copy the built package (msfs-project/Packages) to Community
  python build.py --uninstall  remove CloudSurf from Community

Workflow: python tools/make_cloud_vfx.py (only when the effects change),
python build.py, then in the sim: Dev Mode > open msfs-project/CloudSurf.xml >
Build All, then python build.py --install and restart the sim.

Needs the MSFS 2024 SDK (WASM toolchain) for the module; set MSFS2024_SDK if it
is not in C:\\MSFS 2024 SDK.
"""
import json
import os
import re
import shutil
import stat
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SDK = Path(os.environ.get("MSFS2024_SDK", r"C:\MSFS 2024 SDK"))
LLVM = SDK / "WASM" / "llvm" / "bin"
SYSROOT = SDK / "WASM" / "wasi-sysroot"

PACKAGE = "whisperb0x-cloudsurf"
PROJECT = HERE / "msfs-project"
PROJECT_SRC = PROJECT / "PackageSources"
BUILT_PACKAGE = PROJECT / "Packages" / PACKAGE
VFX_SRC = PROJECT_SRC / "VisualEffectLibs" / "cloudsurf" / "VisualEffectLib"
# Packages of earlier CloudSurf versions that must not run next to this one.
LEGACY_PACKAGES = ["whisperb0x-cloudpassvfx", "whisperb0x-cloudpass"]

PANEL_ID = "PANEL_CLOUDSURF"
PANEL_URL = "html_ui/InGamePanels/CloudSurf/CloudSurf.html"
# Only the name: the sim loads html_ui/icons/toolbar/<name>.svg itself.
ICON_URL = "ICON_TOOLBAR_CLOUDSURF"
PANEL_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<SimBase.Document Type="InGamePanels" version="1,0" id="InGamePanel_CloudSurf">
	<Descr>CloudSurf toolbar panel</Descr>
	<InGamePanels.InGamePanelDefinition id="{PANEL_ID}" name="CloudSurf" url="{PANEL_URL}" resizeDirections="Both" minWidth="22" minHeight="25" defaultWidth="26" defaultHeight="50" defaultTop="20" defaultRight="2" icon="{ICON_URL}" buttonVisible="True"/>
</SimBase.Document>
"""
EFFECTS_PLACEHOLDER = "/*@EFFECTS@*/[]"

# Effect kinds, as in CloudSurf.cpp: 2 = cloud effect (selectable),
# 3 = landing light beam (attached to the aircraft, not selectable).
FX_CLOUD, FX_BEAM = 2, 3


def read_raw(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def write_raw(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def community_folder():
    appdata = Path(os.environ["APPDATA"])
    localappdata = Path(os.environ["LOCALAPPDATA"])
    candidates = [
        localappdata / "Packages" / "Microsoft.Limitless_8wekyb3d8bbwe" / "LocalCache" / "UserCfg.opt",
        appdata / "Microsoft Flight Simulator 2024" / "UserCfg.opt",
    ]
    for cfg in candidates:
        if cfg.exists():
            m = re.search(r'InstalledPackagesPath\s+"([^"]+)"', cfg.read_text(errors="ignore"))
            if m:
                return Path(m.group(1)) / "Community"
    sys.exit("Could not find InstalledPackagesPath in UserCfg.opt")


# --- effects ---------------------------------------------------------------

def own_effects():
    """Our effects as (label, GUID, kind), read from the effect XML (the
    VisualEffect InstanceId is the GUID to spawn). Selectable effects first."""
    lib = read_raw(VFX_SRC / "VisualEffectLibrary.vfxlib")
    effects = []
    for name in re.findall(r'File="([^"]+)"', lib):
        xml = read_raw(VFX_SRC / f"{name}.xml")
        m = re.search(r'<VisualEffect\.VisualEffect InstanceId="\{([0-9A-Fa-f-]+)\}"', xml)
        if m:
            kind = FX_BEAM if name.endswith("Beam") else FX_CLOUD
            effects.append((name, m.group(1).upper(), kind))
    if not effects:
        sys.exit(f"no effects found in {VFX_SRC}; run tools/make_cloud_vfx.py")
    effects.sort(key=lambda e: e[2] == FX_BEAM)
    return effects


def write_effects_header(effects):
    lines = ["// Generated by build.py from msfs-project effect XML. Do not edit.",
             "const Effect kEffects[] = {"]
    for i, (label, guid, kind) in enumerate(effects):
        lines.append(f'\t{{ "{guid}", {kind} }},  // {i} {label}')
    lines.append("};")
    lines.append(f"const int kSelectableEffects = {sum(1 for e in effects if e[2] != FX_BEAM)};")
    (HERE / "src" / "effects_gen.h").write_text("\n".join(lines) + "\n")


# --- module ----------------------------------------------------------------

def compile_wasm(out_wasm):
    if not (LLVM / "clang-cl.exe").exists():
        sys.exit(f"MSFS 2024 SDK WASM toolchain not found in {SDK}; set MSFS2024_SDK")
    obj = HERE / "out" / "CloudSurf.o"
    obj.parent.mkdir(parents=True, exist_ok=True)
    cc = [
        str(LLVM / "clang-cl.exe"), "/c", "/O2", "/std:c++17", "/EHs-c-", "/GS-",
        "--target=wasm32-unknown-wasi",
        f"/clang:--sysroot={SYSROOT}",
        "/Zc:__cplusplus", "/clang:-fstack-size-section", "/clang:-mbulk-memory",
        "/clang:-fvisibility=hidden", "/clang:-ffunction-sections", "/clang:-fdata-sections",
        "/clang:-fno-stack-protector", "/clang:-fno-exceptions", "/clang:-fms-extensions",
        "/clang:-fwritable-strings", "-Werror=return-type", "-Wno-unused-command-line-argument",
        "-Wno-deprecated-declarations", "-Wno-ignored-attributes",
        "/D_MSFS_WASM=1", "/D__wasi__", "/DNDEBUG",
        f"/I{SYSROOT / 'include'}", f"/I{SYSROOT / 'include' / 'c++' / 'v1'}",
        f"/I{SDK / 'WASM' / 'include'}", f"/I{SDK / 'SimConnect SDK' / 'include'}",
        f"/Fo{obj}", str(HERE / "src" / "CloudSurf.cpp"),
    ]
    subprocess.run(cc, check=True)
    lib = SYSROOT / "lib" / "wasm32-wasi"
    ld = [
        str(LLVM / "wasm-ld.exe"), "--no-entry", "--stack-guard-page", "--allow-undefined",
        "--export-dynamic", "--export", "malloc", "--export", "free",
        "--export", "__wasm_call_ctors", "--export-table", "--export", "mallinfo",
        "--export", "mchunkit_begin", "--export", "mchunkit_next",
        "--export", "get_pages_state", "--export", "mark_decommit_pages",
        "-L", str(lib), "-lc++", "-lc++abi", "-lc",
        str(lib / "libclang_rt.builtins-wasm32.a"), "-lc",
        str(SDK / "WASM" / "WasmVersions" / "MSFS_WasmVersions.a"),
        "--export", "GetSimConnectVersion",
        "--gc-sections", "-O3", "--strip-debug",
        "-o", str(out_wasm), str(obj),
    ]
    subprocess.run(ld, check=True)


# --- panel -----------------------------------------------------------------

def panel_html(effects):
    html = read_raw(HERE / "panel" / "standalone.html")
    js = read_raw(HERE / "panel" / "cloudsurf.js")
    js = js.replace(EFFECTS_PLACEHOLDER, json.dumps([label for label, _, kind in effects if kind != FX_BEAM]))
    for marker, text in (("/*@STANDALONE_CSS@*/", read_raw(HERE / "panel" / "standalone.css")),
                         ("/*@CLOUDSURF_CSS@*/", read_raw(HERE / "panel" / "cloudsurf.css")),
                         ("<!--@CLOUDSURF_SECTION@-->", read_raw(HERE / "panel" / "section.html")),
                         ("/*@CLOUDSURF_JS@*/", js)):
        if html.count(marker) != 1:
            sys.exit(f"{marker} missing in panel/standalone.html")
        html = html.replace(marker, text)
    return html


# --- commands --------------------------------------------------------------

def generate():
    effects = own_effects()
    write_effects_header(effects)
    (PROJECT_SRC / "Modules").mkdir(parents=True, exist_ok=True)
    compile_wasm(PROJECT_SRC / "Modules" / "CloudSurf.wasm")
    panel_dir = PROJECT_SRC / "html_ui" / "InGamePanels" / "CloudSurf"
    panel_dir.mkdir(parents=True, exist_ok=True)
    write_raw(panel_dir / "CloudSurf.html", panel_html(effects))
    icon_dir = PROJECT_SRC / "html_ui" / "icons" / "toolbar"
    icon_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(HERE / "panel" / "ICON_TOOLBAR_CLOUDSURF.svg", icon_dir / "ICON_TOOLBAR_CLOUDSURF.svg")
    (PROJECT_SRC / "InGamePanels").mkdir(parents=True, exist_ok=True)
    write_raw(PROJECT_SRC / "InGamePanels" / "InGamePanel_CloudSurf.xml", PANEL_XML)
    print(f"Generated module and panel in {PROJECT_SRC} ({len(effects)} effects)")
    print(f"Next: in the sim, Dev Mode > open {PROJECT / 'CloudSurf.xml'} > Build All, "
          f"then python build.py --install")


def remove_tree(path):
    """rmtree that also clears read-only flags (folders copied from OneDrive
    come read-only). Returns False if something is left, e.g. in use by the sim."""
    def writable_retry(func, p, _exc):
        os.chmod(p, stat.S_IWRITE)
        func(p)
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=writable_retry)
    else:
        shutil.rmtree(path, onerror=writable_retry)
    return not path.exists()


# Asset groups the package builder only copies (see PackageDefinitions): these
# can be refreshed in the built package without the sim. Everything else is
# compiled by Build All.
COPY_GROUPS = ["html_ui", "Modules"]
COMPILED_GROUPS = ["VisualEffectLibs", "MaterialLibs", "InGamePanels"]


def refresh_copies():
    """Bring the copy-only files of the built package up to date with
    PackageSources (module, panel, icon) and fix layout.json and manifest.json
    to match. Stops if compiled sources changed since the last Build All."""
    layout_path = BUILT_PACKAGE / "layout.json"
    # when the sim last compiled (refreshing rewrites layout.json, so not that)
    built_at = max(p.stat().st_mtime for p in (BUILT_PACKAGE / "VisualEffectLibs").rglob("*.spb"))
    # (InGamePanels is compiled too, but build.py rewrites the same XML every run.)
    stale = [p for g in COMPILED_GROUPS if g != "InGamePanels" for p in (PROJECT_SRC / g).rglob("*")
             if p.is_file() and p.stat().st_mtime > built_at + 2]
    if stale:
        sys.exit("Effects or materials changed since the last Build All; build in the sim first:\n  "
                 + "\n  ".join(str(p.relative_to(PROJECT_SRC)) for p in stale))
    layout = json.loads(read_raw(layout_path))
    entries = {e["path"]: e for e in layout["content"]}
    changed = []
    for group in COPY_GROUPS:
        for src in (PROJECT_SRC / group).rglob("*"):
            if not src.is_file():
                continue
            rel = src.relative_to(PROJECT_SRC)
            dst = BUILT_PACKAGE / rel
            if dst.exists() and dst.read_bytes() == src.read_bytes():
                continue
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            st = dst.stat()
            key = rel.as_posix().lower()
            entry = entries.get(key)
            if entry is None:
                entry = {"path": key}
                layout["content"].append(entry)
                entries[key] = entry
            # FILETIME: 100 ns ticks since 1601
            entry["size"] = st.st_size
            entry["date"] = int(st.st_mtime * 10_000_000) + 116444736000000000
            changed.append(key)
    if not changed:
        return
    write_raw(layout_path, json.dumps(layout, indent=2))
    manifest_path = BUILT_PACKAGE / "manifest.json"
    manifest = json.loads(read_raw(manifest_path))
    manifest["total_package_size"] = str(sum(e["size"] for e in layout["content"]))
    write_raw(manifest_path, json.dumps(manifest, indent=2))
    print("Refreshed in the built package: " + ", ".join(changed))


def install(community):
    if not (BUILT_PACKAGE / "layout.json").exists():
        sys.exit(f"Not built yet: {BUILT_PACKAGE}. Build All in the sim first.")
    refresh_copies()
    for name in LEGACY_PACKAGES:
        old = community / name
        if old.exists():
            try:
                done = remove_tree(old)
            except OSError:
                done = False
            print(f"Removed older version {old}" if done else
                  f"Could not fully remove {old}; close the sim and delete it")
    dest = community / PACKAGE
    # File by file: a running sim keeps some files open, removing the folder
    # first would fail halfway.
    locked = []
    for src in BUILT_PACKAGE.rglob("*"):
        if src.is_dir():
            continue
        target = dest / src.relative_to(BUILT_PACKAGE)
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.copy2(src, target)
        except PermissionError:
            locked.append(target)
    print(f"Installed {dest}")
    if locked:
        print(f"{len(locked)} file(s) in use by the sim were not updated; close the sim and run again:")
        for p in locked:
            print(f"  {p}")


def uninstall(community):
    for name in [PACKAGE] + LEGACY_PACKAGES:
        pkg = community / name
        if pkg.exists():
            remove_tree(pkg)
            print(f"Removed {pkg}")


def main():
    args = set(sys.argv[1:])
    if "--install" in args:
        install(community_folder())
    elif "--uninstall" in args:
        uninstall(community_folder())
    else:
        generate()


if __name__ == "__main__":
    main()
