double Rand01() {
	g_rng = g_rng * 1664525u + 1013904223u;
	return (g_rng >> 8) * (1.0 / 16777216.0);
}

void ReadAircraft(Aircraft& a) {
	a.lat = Calc("(A:PLANE LATITUDE, degrees)");
	a.lon = Calc("(A:PLANE LONGITUDE, degrees)");
	a.alt_m = Calc("(A:PLANE ALTITUDE, feet)") * kFtToM;
	a.ve = Calc("(A:VELOCITY WORLD X, feet per second)") * kFtToM;
	a.vu = Calc("(A:VELOCITY WORLD Y, feet per second)") * kFtToM;
	a.vn = Calc("(A:VELOCITY WORLD Z, feet per second)") * kFtToM;
	a.speed = sqrt(a.ve * a.ve + a.vn * a.vn + a.vu * a.vu);
	a.in_cloud = Calc("(A:AMBIENT IN CLOUD, bool)");
	a.cloud_pct = Calc("(A:ENV CLOUD DENSITY, percent)");
	a.camera = Calc("(A:CAMERA STATE, enum)");
	a.time = Calc("(E:SIMULATION TIME, seconds)");
	a.wingspan_m = Calc("(A:WING SPAN, feet)") * kFtToM;
	a.ground_m = Calc("(A:GROUND ALTITUDE, meters)");
}

// L:CLOUDSURF_LAYERS = number of layers (0 = unknown), LAYER<n>_BOT/_TOP in
// feet, above ground when L:CLOUDSURF_LAYERS_AGL is 1, _COV and _DENS.
void ReadLayers(const Aircraft& a) {
	g_layer_count = 0;
	int n = (int)GetL("LAYERS");
	double base = GetL("LAYERS_AGL") > 0.5 ? a.ground_m : 0.0;
	for (int i = 0; i < n && i < kMaxLayers; ++i) {
		char name[32];
		Layer l;
		snprintf(name, sizeof(name), "LAYER%d_BOT", i + 1); l.bot_m = GetL(name) * kFtToM + base;
		snprintf(name, sizeof(name), "LAYER%d_TOP", i + 1); l.top_m = GetL(name) * kFtToM + base;
		snprintf(name, sizeof(name), "LAYER%d_COV", i + 1); l.cov = GetL(name);
		snprintf(name, sizeof(name), "LAYER%d_DENS", i + 1); l.dens = GetL(name);
		if (l.top_m > l.bot_m && l.cov > 0.0) g_layers[g_layer_count++] = l;
	}
	g_layers_real = g_layer_count > 0;
	if (g_layers_real || (g_seen_top <= 0.0 && g_seen_bot <= 0.0)) return;
	double dn = (a.lat - g_seen_lat) / kDeg * kEarthR;
	double de = (a.lon - g_seen_lon) / kDeg * kEarthR * cos(a.lat / kDeg);
	if (dn * dn + de * de > kSeenRadius * kSeenRadius) {
		g_seen_top = g_seen_bot = 0.0;  // somewhere else now
		return;
	}
	Layer l;
	l.bot_m = g_seen_bot > 0.0 ? g_seen_bot : -1e5;
	l.top_m = g_seen_top > 0.0 ? g_seen_top : 1e5;
	l.cov = g_seen_top > 0.0 && g_seen_bot > 0.0 ? 1.0 : 0.0;  // early start only with both known
	l.dens = 1.0;
	g_layers[g_layer_count++] = l;
}

// Top and base of a layer: what was seen of the real deck where known.
double LayerTop(int i) {
	return g_layers_real && g_deck_top[i] > 0.0 ? fmin(g_layers[i].top_m, g_deck_top[i]) : g_layers[i].top_m;
}
double LayerBot(int i) {
	return g_layers_real && g_deck_bot[i] > 0.0 ? fmax(g_layers[i].bot_m, g_deck_bot[i]) : g_layers[i].bot_m;
}

// Forget the learned deck when the weather's layers change.
void CheckLayersChanged() {
	if (!g_layers_real) return;
	double sig = 0.0;
	for (int i = 0; i < g_layer_count; ++i)
		sig += (i + 1) * (g_layers[i].bot_m + 3.0 * g_layers[i].top_m + 7.0 * g_layers[i].cov);
	if (fabs(sig - g_layer_sig) > 1.0) {
		for (int i = 0; i < kMaxLayers; ++i) g_deck_top[i] = g_deck_bot[i] = 0.0;
		g_layer_sig = sig;
	}
}

// Layer containing alt_m (by the weather's band), or -1.
int LayerAt(double alt_m) {
	for (int i = 0; i < g_layer_count; ++i)
		if (alt_m >= g_layers[i].bot_m - kLayerMargin && alt_m <= g_layers[i].top_m + kLayerMargin) return i;
	return -1;
}

// Climbing or descending towards a well covered layer that the flight path
// enters within `reach` metres: returns that layer, or -1.
int LayerAhead(const Aircraft& a, double reach) {
	if (a.speed < 1.0 || fabs(a.vu) < 1.0) return -1;
	double alt_then = a.alt_m + a.vu * reach / a.speed;
	for (int i = 0; i < g_layer_count; ++i) {
		if (g_layers[i].cov < kPreCoverage) continue;
		if (a.vu > 0 && a.alt_m < LayerBot(i) && alt_then >= LayerBot(i)) return i;
		if (a.vu < 0 && a.alt_m > LayerTop(i) && alt_then <= LayerTop(i)) return i;
	}
	return -1;
}

// Offset in metres (east, north, up) from the aircraft to a world position.
void OffsetToWorld(const Aircraft& a, double e, double n, double u,
                   double& lat, double& lon, double& alt_m) {
	lat = a.lat + (n / kEarthR) * kDeg;
	lon = a.lon + (e / (kEarthR * cos(a.lat / kDeg))) * kDeg;
	alt_m = a.alt_m + u;
}

// Distance of a puff along the flight direction (positive = ahead).
double AlongTrack(const Aircraft& a, const Puff& p) {
	double n = (p.lat - a.lat) / kDeg * kEarthR;
	double e = (p.lon - a.lon) / kDeg * kEarthR * cos(a.lat / kDeg);
	double u = p.alt_m - a.alt_m;
	if (a.speed < 1.0) return 0.0;
	return (e * a.ve + n * a.vn + u * a.vu) / a.speed;
}

int PuffIndex(const Puff& p) { return (int)(&p - g_puffs); }

// Retire behind us: no more particles; the ones there live out behind us.
void StopPuff(Puff& p, double now) {
	if (p.state != PUFF_LIVE) return;
	fsVfxStopInstance(p.id);
	p.state = PUFF_STOPPING;
	p.stop_time = now;
}

// Fade a cloud out over kFadeOutPuff, starting after `delay` s (its CloudFade
// reads L:CLOUDSURF_OUT<n>).
void FadeOutPuff(Puff& p, double now, double delay = 0.0) {
	if (p.state != PUFF_LIVE) return;
	char name[24];
	snprintf(name, sizeof(name), "OUT%d", PuffIndex(p));
	SetL(name, now + delay);
	fsVfxStopInstance(p.id);
	p.state = PUFF_FADING;
	p.stop_time = now + delay;
}

bool VerticalExit(const Aircraft& a, double vu) {
	return fabs(vu) >= fmax(kVerticalExit, kVerticalExitSlope * a.speed);
}

// Landing light beam (CloudSurfBeam), attached to the user aircraft. The sim
// evaluates its parameters every frame: strength from the landing lights,
// being in cloud (L:CLOUDSURF_FADE) and darkness; cone direction from two L:vars for tuning.
const char* kBeamRpn =
	"(A:LIGHT LANDING, bool) (L:CLOUDSURF_FADE, number) * "
	"(E:TIME OF DAY, enum) 3 == 0.7 * (E:TIME OF DAY, enum) 0 == (E:TIME OF DAY, enum) 2 == or 0.4 * + 0.3 + * "
	"(L:CLOUDSURF_GLOW, number) *";
FsVfxId g_beam_id = (FsVfxId)FSVFXID_NULL;

int BeamEffect() {
	for (int i = 0; i < kEffectCount; ++i)
		if (kEffects[i].kind == FX_BEAM) return i;
	return -1;
}

void DestroyBeam() {
	if (g_beam_id != (FsVfxId)FSVFXID_NULL) fsVfxDestroyInstance(g_beam_id);
	g_beam_id = (FsVfxId)FSVFXID_NULL;
}

void UpdateBeam() {
	int fx = BeamEffect();
	bool want = fx >= 0 && g_cfg.enable > 0.5 && g_cfg.beam > 0.5 && g_cfg.glow > 0.0;
	if (!want) {
		DestroyBeam();
		return;
	}
	if (g_beam_id != (FsVfxId)FSVFXID_NULL && fsVfxIsValid(g_beam_id)) return;
	FsVfxGraphParam params[3] = {
		{ "Beam", kBeamRpn },
		{ "BeamHeading", "(L:CLOUDSURF_BEAM_HDG, number)" },
		{ "BeamPitch", "(L:CLOUDSURF_BEAM_PITCH, number)" },
	};
	FsVec3d offset = { 0.0, g_cfg.beam_up, g_cfg.beam_fwd };
	FsVec3d pbh = { 0.0, 0.0, 0.0 };
	g_beam_id = fsVfxSpawnOnSimObject(kEffects[fx].guid, 0, nullptr, offset, pbh, -1.f, params, 3);
	if (g_beam_id == (FsVfxId)FSVFXID_NULL) ++g_fails;
}

