double Calc(const char* code) {
	FLOAT64 v = 0;
	execute_calculator_code(code, &v, nullptr, nullptr);
	return v;
}

void SetL(const char* name, double v) {
	char buf[128];
	snprintf(buf, sizeof(buf), "%.6f (>L:CLOUDSURF_%s, number)", v, name);
	execute_calculator_code(buf, nullptr, nullptr, nullptr);
}

double GetL(const char* name) {
	char buf[96];
	snprintf(buf, sizeof(buf), "(L:CLOUDSURF_%s, number)", name);
	return Calc(buf);
}

