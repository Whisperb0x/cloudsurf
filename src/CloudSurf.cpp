// Light from the aircraft, worked out per particle by the effect. Each cloud
// gets the aircraft position (LightX/Y/Z) and the landing light direction
// (BeamX/Y/Z) in its own frame (x right, y up, z along its spawn heading) as
// RPN that the sim evaluates every frame; the effect then measures every
// particle against them, so only the part of a cloud inside the beam or near
// the aircraft lights up. Light strengths, all scaled by L:CLOUDSURF_GLOW:
// landing lights (LandingGlow), and the lights on the aircraft, which share
// one falloff: Airbus-style double strobe and wing lights in white
// (NearWhite), beacon pulse and left nav light in red (NearRed), right nav
// light in green (NearGreen). Distances and cone are in tools/make_cloud_vfx.py.
const char* kNearWhiteRpn =
	"(A:LIGHT STROBE, bool) (E:ABSOLUTE TIME, seconds) 1 % 0.06 < "
	"(E:ABSOLUTE TIME, seconds) 1 % 0.14 > (E:ABSOLUTE TIME, seconds) 1 % 0.2 < and or and 4 * "
	"(A:LIGHT WING, bool) 0.8 * + (L:CLOUDSURF_GLOW, number) *";
const char* kBeaconRpn =
	"(A:LIGHT BEACON, bool) (E:ABSOLUTE TIME, seconds) 1.2 % 0.15 < and 2.5 *";
const char* kLandingRpn = "(A:LIGHT LANDING, bool) 1.6 * (L:CLOUDSURF_GLOW, number) *";

// Shade and opacity by time of day (E:TIME OF DAY: 0 dawn, 1 day, 2 dusk, 3 night).
const char* kShadeRpn =
	"1 (E:TIME OF DAY, enum) 0 == 0.25 * (E:TIME OF DAY, enum) 2 == 0.25 * + "
	"(E:TIME OF DAY, enum) 3 == 0.7 * + -";
const char* kNightAlphaRpn =
	"1 (E:TIME OF DAY, enum) 0 == 0.2 * (E:TIME OF DAY, enum) 2 == 0.2 * + "
	"(E:TIME OF DAY, enum) 3 == 0.5 * + -";

// RPN for the aircraft position relative to a cloud spawned at lat/lon/alt
// with heading hdg (radians), in the cloud's frame: axis 0 = x (right),
// 1 = y (up), 2 = z (forward).
void LightRpn(char* out, size_t n, int axis, double lat, double lon, double alt_m, double hdg) {
	char de[96], dn[96];
	snprintf(de, sizeof(de), "(A:PLANE LONGITUDE, degrees) %.8f - %.3f *", lon, 111320.0 * cos(lat / 57.29577951308232));
	snprintf(dn, sizeof(dn), "(A:PLANE LATITUDE, degrees) %.8f - 111320 *", lat);
	if (axis == 1) snprintf(out, n, "(A:PLANE ALTITUDE, meters) %.2f -", alt_m);
	else if (axis == 0) snprintf(out, n, "%s %.6f * %s %.6f * -", de, cos(hdg), dn, sin(hdg));
	else snprintf(out, n, "%s %.6f * %s %.6f * +", de, sin(hdg), dn, cos(hdg));
}

// RPN for the landing light direction (unit vector) in the frame of a cloud
// spawned with heading hdg (radians); follows the aircraft's heading and
// pitch plus L:CLOUDSURF_BEAM_HDG/PITCH.
void BeamDirRpn(char* out, size_t n, int axis, double hdg) {
	const char* pitch = "(A:PLANE PITCH DEGREES, radians) neg (L:CLOUDSURF_BEAM_PITCH, number) 0.0174533 * +";
	char rel[160];
	snprintf(rel, sizeof(rel),
	         "(A:PLANE HEADING DEGREES TRUE, radians) (L:CLOUDSURF_BEAM_HDG, number) 0.0174533 * + %.6f -", hdg);
	if (axis == 1) snprintf(out, n, "%s sin", pitch);
	else snprintf(out, n, "%s cos %s %s *", pitch, rel, axis == 0 ? "sin" : "cos");
}

// RPN: metres the point lies to the right of the aircraft (negative = left).
void SideRpn(char* out, size_t n, double lat, double lon) {
	snprintf(out, n,
	         "%.8f (A:PLANE LONGITUDE, degrees) - %.3f * (A:PLANE HEADING DEGREES TRUE, radians) cos * "
	         "%.8f (A:PLANE LATITUDE, degrees) - 111320 * (A:PLANE HEADING DEGREES TRUE, radians) sin * -",
	         lon, 111320.0 * cos(lat / 57.29577951308232), lat);
}

