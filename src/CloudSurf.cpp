// RPN for the aircraft position relative to a cloud spawned at lat/lon/alt
// with heading hdg (radians), in the cloud's frame: axis 0 = x (right),
// 1 = y (up), 2 = z (forward).
void LightRpn(char* out, size_t n, int axis, double lat, double lon, double alt_m, double hdg) {
	char de[96], dn[96];
	snprintf(de, sizeof(de), "(A:PLANE LONGITUDE, degrees) %.8f - %.3f *", lon, 111320.0 * cos(lat / 57.29577951308232));
	snprintf(dn, sizeof(dn), "(A:PLANE LATITUDE, degrees) %.8f - 111320 *", lat);
	if (axis == 1) snprintf(out, n, "(A:PLANE ALTITUDE, meters) %.2f -", alt_m);
	else if (axis == 0) snprintf(out, n, "%s %.6f * %s %.6f * -", de, cos(hdg), dn, sin(hdg));
	else snprintf(out, n, "%s %.6f * %s %.6f * +", de, sin(hdg), dn, cos(hdg));
}

// RPN for the landing light direction (unit vector) in the frame of a cloud
// spawned with heading hdg (radians); follows the aircraft's heading and
// pitch plus L:CLOUDSURF_BEAM_HDG/PITCH.
void BeamDirRpn(char* out, size_t n, int axis, double hdg) {
	const char* pitch = "(A:PLANE PITCH DEGREES, radians) neg (L:CLOUDSURF_BEAM_PITCH, number) 0.0174533 * +";
	char rel[160];
	snprintf(rel, sizeof(rel),
	         "(A:PLANE HEADING DEGREES TRUE, radians) (L:CLOUDSURF_BEAM_HDG, number) 0.0174533 * + %.6f -", hdg);
	if (axis == 1) snprintf(out, n, "%s sin", pitch);
	else snprintf(out, n, "%s cos %s %s *", pitch, rel, axis == 0 ? "sin" : "cos");
}

// RPN: metres the point lies to the right of the aircraft (negative = left).
void SideRpn(char* out, size_t n, double lat, double lon) {
	snprintf(out, n,
	         "%.8f (A:PLANE LONGITUDE, degrees) - %.3f * (A:PLANE HEADING DEGREES TRUE, radians) cos * "
	         "%.8f (A:PLANE LATITUDE, degrees) - 111320 * (A:PLANE HEADING DEGREES TRUE, radians) sin * -",
	         lon, 111320.0 * cos(lat / 57.29577951308232), lat);
}

