// Effects CloudPass can spawn, selected with L:CLOUDPASS_EFFECT. The list is
// generated by build.py from the effect XML. kind: 2 = cloud effect taking
// our graph parameters, 3 = landing light beam (attached to the aircraft).
enum { FX_CLOUDPASS = 2, FX_BEAM = 3 };
struct Effect { const char* guid; int kind; };
#include "effects_gen.h"
const int kEffectCount = sizeof(kEffects) / sizeof(kEffects[0]);

// Emissive glow for our own effect. The sim evaluates these RPN expressions
// every frame, so each cloud gets its own copy with its position baked in:
// the glow falls off with the distance to the aircraft, and only clouds near
// the lights light up. Airbus-style double strobe and landing lights in white,
// beacon pulse in red, all scaled by L:CLOUDPASS_GLOW.
const char* kStrobeRpn =
	"(A:LIGHT STROBE, bool) (E:ABSOLUTE TIME, seconds) 1 % 0.06 < "
	"(E:ABSOLUTE TIME, seconds) 1 % 0.14 > (E:ABSOLUTE TIME, seconds) 1 % 0.2 < and or and";
const char* kBeaconRpn =
	"(A:LIGHT BEACON, bool) (E:ABSOLUTE TIME, seconds) 1.2 % 0.15 < and";
const double kStrobeReach = 60.0;   // m
const double kLandingReach = 600.0; // m, like the long volumetric beams of PMDG/iFly
const double kStrobeNear = 15.0;    // m where strobe light is still at half strength
const double kLandingNear = 120.0;  // m where landing light is still at half strength
const double kLandingCone = 0.978;  // cos of the beam half angle (~12 deg)
const double kGlowFlatten = 3.0;    // vertical distance counts this much more: flat glow

// Shade and opacity by time of day (E:TIME OF DAY: 0 dawn, 1 day, 2 dusk, 3 night).
const char* kShadeRpn =
	"1 (E:TIME OF DAY, enum) 0 == 0.25 * (E:TIME OF DAY, enum) 2 == 0.25 * + "
	"(E:TIME OF DAY, enum) 3 == 0.7 * + -";
const char* kNightAlphaRpn =
	"1 (E:TIME OF DAY, enum) 0 == 0.2 * (E:TIME OF DAY, enum) 2 == 0.2 * + "
	"(E:TIME OF DAY, enum) 3 == 0.5 * + -";

// RPN for the distance in metres from the aircraft to a fixed point, with
// the vertical part weighted by kGlowFlatten.
void DistanceRpn(char* out, size_t n, double lat, double lon, double alt_m) {
	snprintf(out, n,
	         "(A:PLANE LATITUDE, degrees) %.8f - 111320 * sqr "
	         "(A:PLANE LONGITUDE, degrees) %.8f - %.3f * sqr + "
	         "(A:PLANE ALTITUDE, meters) %.2f - %.1f * sqr + sqrt",
	         lat, lon, 111320.0 * cos(lat / 57.29577951308232), alt_m, kGlowFlatten);
}

// RPN for light intensity over distance: bright close by, softly fading
// (1 / (1 + (d/near)^2)) and reaching zero at `reach`.
void FalloffRpn(char* out, size_t n, const char* dist, double near_m, double reach_m) {
	snprintf(out, n, "%s %.1f / sqr 1 + 1 r / %s %.1f / 1 r - 0 max *", dist, near_m, dist, reach_m);
}

// RPN 0..1: how far the point lies inside the landing light beam (ahead of
// the nose, within kLandingCone of the heading).
void BeamRpn(char* out, size_t n, double lat, double lon) {
	double k = 111320.0 * cos(lat / 57.29577951308232);
	snprintf(out, n,
	         "%.8f (A:PLANE LATITUDE, degrees) - 111320 * (A:PLANE HEADING DEGREES TRUE, radians) cos * "
	         "%.8f (A:PLANE LONGITUDE, degrees) - %.3f * (A:PLANE HEADING DEGREES TRUE, radians) sin * + "
	         "%.8f (A:PLANE LATITUDE, degrees) - 111320 * sqr %.8f (A:PLANE LONGITUDE, degrees) - %.3f * sqr + sqrt 1 max / "
	         "%.3f - %.3f / 0 max 1 min",
	         lat, lon, k, lat, lon, k, kLandingCone, 1.0 - kLandingCone);
}

