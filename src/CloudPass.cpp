// CloudPass - standalone WASM module for MSFS 2024.
//
// While the aircraft is inside a cloud, CloudPass spawns small clouds (our own
// visual effects, see tools/make_cloud_vfx.py) at fixed world positions ahead
// of the aircraft, so you fly through clouds that pass the windows and wings
// instead of a static fog that moves with you. Clouds behind are stopped and
// destroyed; when you leave the cloud the ones still ahead are stopped too.
// Amount, opacity and colour follow the sim's cloud density and the time of
// day; clouds near the aircraft lights glow, and a landing light beam effect
// is attached to the aircraft.
//
// Licensed CC BY-NC-SA 4.0. Everything is tuned live through L:CLOUDPASS_*
// vars (see kConfigVars), no rebuild needed.

#include <MSFS/MSFS.h>
#include <MSFS/MSFS_Vfx.h>
